#  Objetivo: Acá quedan los operadores aritmeticos comunes, podemos hacer sumas
#            restas, multiplicaciones, divisiones, modulos, potencias, etc.
#===============================================================================
# variables
a = 10
b = 2

# Suma
suma = a + b

# Resta
resta = a - b

# Multiplicacion
producto = a * b

# Division
division = a / b

# Modulo 
modulo = a % b

# Potencia
potencia = a ** b

# Impresiones
print (f"SUMA = {suma} \nRESTA = {resta} \nProducto = {producto} \nModulo = {modulo} \nPotencia = {potencia}")